import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
const listen=s=>new Promise(r=>s.listen(0,'127.0.0.1',()=>r(s.address().port)));
const wait=async(fn)=>{for(let i=0;i<150;i++){try{const x=await fn();if(x)return x;}catch{}await new Promise(r=>setTimeout(r,30));}throw Error('Timed out');};
test('native inbox creates a fresh coordinator, sleeps, queues and resumes without chat prompts',async(t)=>{
 const dir=await mkdtemp(path.join(tmpdir(),'swarm-test-'));const calls=[],statuses=new Map();let created=0;
 const host=http.createServer(async(req,res)=>{let s='';for await(const c of req)s+=c;const {method,input}=JSON.parse(s);calls.push({method,input});let result={ok:true};if(method==='sessions.status')result={status:statuses.get(input.sessionId)||'idle'};if(method==='sessions.stop')result={stopped:true};res.setHeader('Content-Type','application/json');res.end(JSON.stringify({result}));});
 const hp=await listen(host);const probe=http.createServer();const port=await listen(probe);await new Promise(r=>probe.close(r));
 const proc=spawn(process.execPath,['service/main.js'],{env:{...process.env,HOME:dir,OPENCHAMBER_SERVICE_PORT:String(port),OPENCHAMBER_SERVICE_TOKEN:'test-token',OPENCHAMBER_SERVICE_DATA_DIR:dir,OPENCHAMBER_HOST_CALLBACK_URL:'http://127.0.0.1:'+hp},stdio:'ignore'});
 let quit=false,bridge;
 t.after(async()=>{quit=true;await bridge;proc.kill();await new Promise(r=>host.close(r));await rm(dir,{force:true,recursive:true});});
 const req=async(p,b)=>{const r=await fetch('http://127.0.0.1:'+port+p,{method:b?'POST':'GET',headers:{Authorization:'Bearer test-token','Content-Type':'application/json'},...(b?{body:JSON.stringify(b)}:{})});assert.equal(r.status,200);return r.json();};
 await wait(()=>req('/health'));
 const nativeCalls=[];
 bridge=(async()=>{while(!quit){const {job}=await req('/bridge/poll',{});if(job){nativeCalls.push(job);let result;if(job.op==='create'){created++;result={id:job.input.id};statuses.set(result.id,'idle');}else{assert.equal(job.op,'wake');statuses.set(job.input.sessionID,'busy');result={id:job.input.id};}await req('/bridge/result',{id:job.id,result});}await new Promise(r=>setTimeout(r,20));}})();
 const s=await req('/start',{task:'Implement test',directory:'/repo',sessionId:null});
 const state=async()=> (await req('/list?directory=%2Frepo'))[0];
 const member=async n=>(await state()).members.find(m=>m.name===n);
 const agent=(sessionId,action,input)=>req('/agent',{sessionId,action,input});
 const end=async(id,num)=>{statuses.set(id,'idle');await req('/session-events',{event:{id:'evt-'+num,type:'turn-finished',session:{id}},content:{reply:'done'}});};
 const coord=await wait(async()=>{const m=await member('coordinator');return m.state==='active'&&m;});
 assert.ok(coord.sessionId.startsWith('ses_'));
 await agent(coord.sessionId,'add',{name:'fix',brief:'Fix issue',paths:['x.js']});
 const w=await wait(async()=>{const m=await member('fix');return m?.state==='active'&&m;});
 assert.equal(created,2);
 await end(coord.sessionId,1);await wait(async()=> (await member('coordinator')).state==='waiting');
 await req('/message',{id:s.id,to:'fix',text:'Extra acceptance criterion'});
 assert.equal((await member('fix')).pending,1);
 assert.equal(nativeCalls.filter(c=>c.op==='wake'&&c.input.sessionID===w.sessionId).length,1);
 await end(w.sessionId,2);
 const wake=await wait(()=>nativeCalls.filter(c=>c.op==='wake'&&c.input.sessionID===w.sessionId)[1]);
 assert.equal(wake.input.resume,true);assert.equal(wake.input.delivery,'queue');assert.doesNotMatch(wake.input.text,/Extra acceptance/);
 const board=await agent(w.sessionId,'read',{});assert.ok(board.posts.some(p=>p.text==='Extra acceptance criterion'));
 assert.equal(created,2);await end(w.sessionId,3);await wait(async()=> (await member('fix')).state==='waiting');
 await agent(w.sessionId,'post',{to:['coordinator'],text:'Test result',kind:'done'});
 const cw=await wait(()=>nativeCalls.filter(c=>c.op==='wake'&&c.input.sessionID===coord.sessionId)[1]);assert.doesNotMatch(cw.input.text,/Test result/);
 assert.equal((await member('fix')).sessionId,w.sessionId);assert.equal(calls.filter(c=>['sessions.start','sessions.send'].includes(c.method)).length,0);
 await req('/stop',{id:s.id});assert.equal((await state()).status,'stopped');
});
